    var value = source
    TRADITIONAL_PHRASES.forEach { (simplified, traditional) -> value = value.replace(simplified, traditional) }
    return buildString(value.length) {
        value.forEach { append(TRADITIONAL_CHARS[it] ?: it) }
    }
}

