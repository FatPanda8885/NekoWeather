import androidx.compose.runtime.staticCompositionLocalOf
import com.neko.weather.model.AppLanguage

val LocalAppLanguage = staticCompositionLocalOf { AppLanguage.SIMPLIFIED_CHINESE }

fun localizedText(text: String, language: AppLanguage): String = when (language) {
    AppLanguage.SIMPLIFIED_CHINESE -> text
    AppLanguage.TRADITIONAL_CHINESE -> toTraditionalChinese(text)
    AppLanguage.ENGLISH -> toEnglish(text)
    AppLanguage.JAPANESE -> toJapanese(text)
}

private fun toEnglish(source: String): String {
    var value = source
    ENGLISH_REPLACEMENTS.sortedByDescending { it.first.length }.forEach { (zh, en) -> value = value.replace(zh, en) }
    return value
}

